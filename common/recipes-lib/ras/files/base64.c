/**
 *
 * Caller is responsible for freeing the returned buffer.
 */
uint8_t *base64_decode(const char *src, int32_t len, int32_t *out_len)
{
	uint8_t *out;
	uint8_t *pos;
	uint8_t block[4];
	uint8_t tmp;
	int32_t block_index;
	int32_t src_index;
	uint32_t pad_count = 0;

	if (!out_len) {
		return NULL;
	}

	// Malloc might be up to 2 larger dependent on padding
	*out_len = len / 4 * 3;
	pos = out = malloc(*out_len);
	if (out == NULL) {
		return NULL;
	}

	block_index = 0;
	for (src_index = 0; src_index < len; src_index++) {
		tmp = decode_table[(uint8_t)src[src_index]];
		if (tmp == 0x80) {
			free(out);
			return NULL;
		}

		if (src[src_index] == '=') {
			pad_count++;
		}

		block[block_index] = tmp;
		block_index++;
		if (block_index == 4) {
			*pos++ = (block[0] << 2) | (block[1] >> 4);
			*pos++ = (block[1] << 4) | (block[2] >> 2);
			*pos++ = (block[2] << 6) | block[3];
			if (pad_count > 0) {
				if (pad_count == 1) {
					pos--;
				} else if (pad_count == 2) {
					pos -= 2;
				} else {
					/* Invalid pad_counting */
					free(out);
					return NULL;
				}
				break;
			}
			block_index = 0;
		}
	}

	*out_len = pos - out;
	return out;
}
